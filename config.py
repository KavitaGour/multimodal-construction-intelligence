def load_dotenv_file(path: str = ".env") -> None:
    """Tiny dependency-free .env loader: KEY=VALUE lines -> os.environ (never overrides real env vars)."""
    import os

    full = path if os.path.isabs(path) else os.path.join(os.path.dirname(os.path.abspath(__file__)), path)
    try:
        with open(full, encoding="utf-8") as fh:
            for line in fh:
                line = line.strip()
                if not line or line.startswith("#") or "=" not in line:
                    continue
                key, _, value = line.partition("=")
                key, value = key.strip(), value.strip().strip('"').strip("'")
                if key and value:
                    os.environ.setdefault(key, value)
    except OSError:
        pass  # no .env file is perfectly fine
